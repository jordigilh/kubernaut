// DemoHelmOptions configures the operator-backed demo for either local or fleet
// topology. Options-pattern struct (AGENTS.md 8-parameter limit) keeps the
// shared deployment stable as the two entry points evolve.
//
// LLMCredentialsFile is handled separately from the non-sensitive deployment options:
// it is written into the cluster as the demoLLMSecretName Secret after the
// cluster exists and before the user-owned Kubernaut CR is applied.
type DemoHelmOptions struct {
	// Mode selects local or fleet-specific operator configuration and infrastructure
	// wiring.
	Mode DemoMode
	// Autonomous, when true, sets gateway.enabled=true so AlertManager-sourced
	// signals auto-create RemediationRequests. false (the default) leaves
	// Gateway disabled -- Prometheus/AlertManager still fire real alerts, but
	// nothing auto-remediates until the user asks Console to investigate, so
	// a new user experiences the remediation flow deliberately before opting
	// into the fully autonomous one.
	Autonomous bool
	// LLMProvider/LLMModel/LLMEndpoint configure spec.llmProfiles.primary.*
	// -- required, no hardcoded default (varies per user's own LLM provider,
	// same reason the split-infra design never baked these into shared
	// test-infra Go code). Not sensitive -- these become CR fields, not
	// Secret material.
	LLMProvider string
	LLMModel    string
	LLMEndpoint string
	// LLMReasoningEnabled and LLMReasoningEffort are optional demo overrides.
	// A nil Enabled value and empty Effort value select the conservative
	// provider/model default; explicit values win over that default.
	LLMReasoningEnabled *bool
	LLMReasoningEffort  string
	// LLMCredentialsFile contains the raw provider credential material to write
	// into the cluster after Kind exists and before the operator CR is applied.
	LLMCredentialsFile string
	// SPPolicyFile/AAPolicyFile override the baked-in demo Rego policies
	// (demoDefaultSPPolicyRego/demoDefaultAAPolicyRego -- a
	// catch-all classification policy and an unconditional
	// "always require approval" gate, respectively) with a user-supplied
	// file. Empty uses the baked-in defaults; neither policy is embedded in the
	// operator chart and both are supplied through the user-owned CR contract.
	SPPolicyFile string
	AAPolicyFile string
	// ImageTag optionally overrides the published prebuilt image tag for the demo.
	ImageTag string
	// ImageRepository optionally overrides the base repository for the demo's
	// prebuilt Kubernaut service images. A trailing slash is ignored.
	ImageRepository string
	// VertexProject/VertexLocation feed global.llmProfiles.primary.vertexProject
	// / vertexLocation -- required by the chart when LLMProvider is vertex_ai
	// (the provider hosts Claude/Gemini models and derives its endpoint from
	// project/location). Empty for every other provider; no --set is emitted
	// then, keeping non-Vertex renders unchanged.
	VertexProject  string
	VertexLocation string
	// OperatorArtifacts selects immutable prebuilt operator/application inputs.
	// Empty values resolve the selected published v1.6 release line; a source
	// checkout is never used unless explicitly configured through the
	// KUBERNAUT_OPERATOR_ROOT development override.
	OperatorArtifacts DemoArtifactOverrides
	// Exposure is allocated before Kind creation when the demo needs stable host
	// access. The adapter remains upstream test-owned and is never added to the CR.
	Exposure *OperatorExposurePlan
}

// DemoMode identifies the cluster topology for the demo setup command.
type DemoMode string

const (
	DemoModeLocal DemoMode = "local"
	DemoModeFleet DemoMode = "fleet"
)

// resolveDemoReasoning returns the effective demo reasoning settings and the
// runtime capability override needed for explicitly configured custom endpoints.
// The demo only infers support for the first-party OpenAI provider: a custom
// OpenAI-compatible endpoint must opt in explicitly because a GPT-like model
// name does not prove that the endpoint accepts reasoning_effort.
func resolveDemoReasoning(o DemoHelmOptions) (enabled bool, effort, capabilityOverride string) {
	if o.LLMProvider == sharedtypes.LLMProviderOpenAI {
		effort = openaicompat.DefaultOpenAIReasoningEffort(o.LLMModel)
		enabled = effort != ""
	}

	explicit := o.LLMReasoningEnabled != nil || o.LLMReasoningEffort != ""
	if o.LLMReasoningEnabled != nil {
		enabled = *o.LLMReasoningEnabled
	}
	if o.LLMReasoningEffort != "" {
		effort = o.LLMReasoningEffort
		if o.LLMReasoningEnabled == nil {
			enabled = true
		}
	}
	if !enabled {
		effort = ""
	}
	if explicit && (o.LLMProvider == sharedtypes.LLMProviderOpenAI || o.LLMProvider == sharedtypes.LLMProviderOpenAICompatible) {
		if enabled {
			capabilityOverride = "force_on"
		} else {
			capabilityOverride = "force_off"
		}
	}
	return enabled, effort, capabilityOverride
}

// Validate reports every missing required flag in one error, so
// hack/setup-demo-infra's caller can tell the user everything they need to
// fix in a single run instead of one flag at a time.
func (o DemoHelmOptions) Validate() error {
	var missing []string
	if o.LLMProvider == "" {
		missing = append(missing, "-llm-provider")
	}
	if o.LLMModel == "" {
		missing = append(missing, "-llm-model")
	}
	// Endpoint is required for every provider except vertex_ai, whose
	// endpoint is derived from project/location by the SDK (issue #2355) --
	// mirrors the platform contract in pkg/shared/types LLMConfig
	// validateProviderRequiredFields (endpoint required only for
	// openai/openai_compatible).
	if o.LLMEndpoint == "" && o.LLMProvider != sharedtypes.LLMProviderVertexAI {
		missing = append(missing, "-llm-endpoint")
	}
	if o.LLMProvider == sharedtypes.LLMProviderVertexAI {
		if o.VertexProject == "" {
			missing = append(missing, "-vertex-project")
		}
		if o.VertexLocation == "" {
			missing = append(missing, "-vertex-location")
		}
	}
	if len(missing) > 0 {
		return fmt.Errorf("missing required flags: %s", strings.Join(missing, ", "))
	}
	if o.LLMReasoningEffort != "" {
		if err := sharedtypes.ValidateReasoningConfig("llm", &sharedtypes.LLMReasoningConfig{Effort: o.LLMReasoningEffort}, o.LLMProvider); err != nil {
			return err
		}
	}
	enabled, effort, _ := resolveDemoReasoning(o)
	if err := sharedtypes.ValidateReasoningConfig("llm", &sharedtypes.LLMReasoningConfig{Enabled: enabled, Effort: effort}, o.LLMProvider); err != nil {
		return err
	}
	return nil
}

func isLocalDemoImageRepository(repository string) bool {
	repository = strings.TrimRight(repository, "/")
	return repository == "localhost" || strings.HasPrefix(repository, "localhost/")
}

func demoLocalImageReferences(repository, tag string) []string {
	repository = strings.TrimRight(repository, "/")
	images := make([]string, 0, len(demoLocalImageServices))
	for _, service := range demoLocalImageServices {
		images = append(images, fmt.Sprintf("%s/%s:%s", repository, service, tag))
	}
	return images
}

func loadDemoImagesToKind(ctx context.Context, clusterName string, opts DemoHelmOptions, writer io.Writer) error {
	if opts.ImageRepository == "" || opts.ImageTag == "" || !isLocalDemoImageRepository(opts.ImageRepository) {
		return nil
	}
	if clusterName == "" {
		return fmt.Errorf("kind cluster name is required when loading local demo images")
	}

	images := demoLocalImageReferences(opts.ImageRepository, opts.ImageTag)
	for i, image := range images {
		if err := LoadImageToKind(ctx, image, demoLocalImageServices[i], clusterName, writer); err != nil {
			return fmt.Errorf("failed to load local demo image %s into Kind cluster %q: %w", image, clusterName, err)
		}
	}
	return nil
}
